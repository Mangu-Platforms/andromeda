import type { ProjectSpec } from "../spec/types.ts";
import type { GeneratedFile, TemplateDefinition } from "./types.ts";
import { envExample, stableJson } from "./render.ts";
import { migrationSql } from "./sql.ts";

const DEPENDENCIES = {};
const DEV_DEPENDENCIES = {
  wrangler: "4.125.0",
  "@cloudflare/workers-types": "5.20260820.1",
  typescript: "5.9.3",
};

/**
 * Headless API on Cloudflare Workers.
 *
 * Shares the `features/contract.ts` boundary with the Next.js template, so a
 * generated feature module and its tests are portable between the two: the
 * template owns routing and the runtime, the model owns pure logic only.
 */
export const workerApi: TemplateDefinition = {
  id: "worker-api",
  version: "1.0.0",
  description:
    "Cloudflare Workers HTTP API with Supabase Postgres. No UI; edge-deployed endpoints only.",
  dependencies: DEPENDENCIES,
  devDependencies: DEV_DEPENDENCIES,
  render(spec: ProjectSpec): GeneratedFile[] {
    return [
      { path: "package.json", contents: packageJson(spec) },
      { path: "tsconfig.json", contents: tsconfig() },
      { path: "wrangler.toml", contents: wranglerToml(spec) },
      { path: ".gitignore", contents: ".wrangler/\nnode_modules/\n.env\n.dev.vars\n" },
      { path: ".env.example", contents: envExample(spec) },
      { path: "README.md", contents: readme(spec) },
      { path: ".github/workflows/ci.yml", contents: ciWorkflow() },
      { path: "supabase/migrations/0001_init.sql", contents: migrationSql(spec) },
      { path: "features/contract.ts", contents: featureContract() },
      { path: "src/router.ts", contents: router(spec) },
      { path: "src/index.ts", contents: entrypoint(spec) },
    ];
  },
};

function packageJson(spec: ProjectSpec): string {
  return stableJson({
    name: spec.name,
    version: "0.1.0",
    private: true,
    type: "module",
    engines: { node: ">=22.18.0" },
    imports: { "#features/*": "./features/*" },
    scripts: {
      dev: "wrangler dev",
      deploy: "wrangler deploy",
      typecheck: "tsc --noEmit",
      test: 'node --test "features/**/*.test.ts"',
    },
    dependencies: DEPENDENCIES,
    devDependencies: DEV_DEPENDENCIES,
  });
}

const tsconfig = (): string =>
  stableJson({
    compilerOptions: {
      target: "ES2023",
      lib: ["ES2023"],
      module: "NodeNext",
      moduleResolution: "nodenext",
      allowImportingTsExtensions: true,
      rewriteRelativeImportExtensions: true,
      verbatimModuleSyntax: true,
      erasableSyntaxOnly: true,
      noEmit: true,
      strict: true,
      noUncheckedIndexedAccess: true,
      skipLibCheck: true,
      types: ["@cloudflare/workers-types"],
    },
    include: ["**/*.ts"],
    exclude: ["node_modules"],
  });

function wranglerToml(spec: ProjectSpec): string {
  const vars = spec.env
    .filter((e) => !e.secret)
    .map((e) => `# ${e.name} — ${e.description}`)
    .join("\n");
  const secrets = spec.env
    .filter((e) => e.secret)
    .map((e) => `#   wrangler secret put ${e.name}`)
    .join("\n");

  return `name = "${spec.name}"
main = "src/index.ts"
compatibility_date = "2026-01-01"

[vars]
${vars || "# no plain-text vars"}

# Secrets are never written to this file. Set them with:
${secrets || "#   (no secrets declared)"}
`;
}

