const featureContract = (): string =>
  `/** Shared with every Andromeda template: a feature is a pure request handler. */
export interface FeatureInput {
  method: string;
  path: string;
  query: Record<string, string>;
  body: unknown;
  userId: string | null;
}

export interface FeatureResult {
  status: number;
  body: unknown;
}

export type FeatureHandler = (input: FeatureInput) => Promise<FeatureResult>;
`;

function router(spec: ProjectSpec): string {
  const routed = spec.routes.filter((r) => r.feature);
  const imports = [...new Set(routed.map((r) => r.feature))]
    .map((f) => `import { handle as ${camel(f)} } from "#features/${f}.ts";`)
    .join("\n");
  const table = routed
    .map((r) => `  { method: ${JSON.stringify(r.method)}, path: ${JSON.stringify(r.path)}, handler: ${camel(r.feature)} },`)
    .join("\n");

  return `import type { FeatureHandler } from "#features/contract.ts";
${imports}

export interface Route {
  method: string;
  path: string;
  handler: FeatureHandler;
}

export const routes: Route[] = [
${table}
];
`;
}

function entrypoint(spec: ProjectSpec): string {
  return `import { routes } from "./router.ts";

/**
 * Deterministic request plumbing for ${spec.name}. Generated features never
 * parse requests or shape errors themselves.
 */
export default {
  async fetch(request: Request): Promise<Response> {
    const url = new URL(request.url);

    if (url.pathname === "/health") {
      return Response.json({ ok: true, service: ${JSON.stringify(spec.name)} });
    }

    const route = routes.find(
      (r) => r.method === request.method && r.path === url.pathname,
    );
    if (!route) return Response.json({ error: "not found" }, { status: 404 });

    let body: unknown = null;
    if (request.method !== "GET" && request.method !== "DELETE") {
      try {
        body = await request.json();
      } catch {
        return Response.json({ error: "request body must be JSON" }, { status: 400 });
      }
    }

    const result = await route.handler({
      method: request.method,
      path: url.pathname,
      query: Object.fromEntries(url.searchParams),
      body,
      userId: request.headers.get("x-user-id"),
    });

    return Response.json(result.body, { status: result.status });
  },
};
`;
}

const camel = (name: string): string => {
  const pascal = name
    .split(/[_-]/)
    .filter(Boolean)
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join("");
  return `${pascal.slice(0, 1).toLowerCase()}${pascal.slice(1)}`;
};
