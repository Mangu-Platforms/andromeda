/**
 * Deterministic adapter between an HTTP route and a generated feature module.
 * The model never writes this part, so request parsing, the auth lookup and
 * error shaping are identical in every generated project.
 */
function featureRoute(spec: ProjectSpec, path: string): string {
  const methods = spec.routes
    .filter((r) => r.path === path && r.feature)
    .map((r) => ({ method: r.method, feature: r.feature }));

  const imports = [...new Set(methods.map((m) => m.feature))]
    .map((feature) => `import { handle as ${camel(feature)} } from "#features/${feature}.ts";`)
    .join("\n");

  const handlers = methods
    .map(
      ({ method, feature }) => `export async function ${method}(request: Request) {
  return run(request, ${camel(feature)});
}`,
    )
    .join("\n\n");

  return `import type { FeatureHandler } from "#features/contract.ts";
import { supabaseServer } from "#lib/supabase.ts";
${imports}

async function run(request: Request, handler: FeatureHandler) {
  const url = new URL(request.url);
  let body: unknown = null;
  if (request.method !== "GET" && request.method !== "DELETE") {
    try {
      body = await request.json();
    } catch {
      return Response.json({ error: "request body must be JSON" }, { status: 400 });
    }
  }

  const supabase = await supabaseServer();
  const { data } = await supabase.auth.getUser();

  const result = await handler({
    method: request.method,
    path: url.pathname,
    query: Object.fromEntries(url.searchParams),
    body,
    userId: data.user?.id ?? null,
  });

  return Response.json(result.body, { status: result.status });
}

${handlers}
`;
}

const pascal = (name: string): string =>
  name
    .split(/[_-]/)
    .filter(Boolean)
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join("");

const camel = (name: string): string => {
  const p = pascal(name);
  return `${p.slice(0, 1).toLowerCase()}${p.slice(1)}`;
};

/** JSX text is not HTML: braces and angle brackets become string expressions. */
const escapeJsx = (text: string): string =>
  text.replace(/[{}<>]/g, (c) => `{${JSON.stringify(c)}}`);
