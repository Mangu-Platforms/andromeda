const DEPENDENCIES = {
  next: "16.3.1",
  react: "19.2.8",
  "react-dom": "19.2.8",
  "@supabase/supabase-js": "2.112.3",
  "@supabase/ssr": "0.12.4",
};

const DEV_DEPENDENCIES = {
  typescript: "5.9.3",
  "@types/node": "26.2.0",
  "@types/react": "19.2.18",
  "@types/react-dom": "19.2.4",
};

export const nextSupabaseApp: TemplateDefinition = {
  id: "next-supabase-app",
  version: "1.0.0",
  description:
    "Next.js App Router on Vercel with Supabase Postgres, auth and row-level security.",
  dependencies: DEPENDENCIES,
  devDependencies: DEV_DEPENDENCIES,
  render(spec: ProjectSpec): GeneratedFile[] {
    const files: GeneratedFile[] = [
      { path: "package.json", contents: packageJson(spec) },
      { path: "tsconfig.json", contents: tsconfig() },
      { path: "next.config.mjs", contents: nextConfig() },
      { path: ".gitignore", contents: gitignore() },
      { path: ".env.example", contents: envExample(spec) },
      { path: "README.md", contents: readme(spec) },
      { path: ".github/workflows/ci.yml", contents: ciWorkflow() },
      { path: "supabase/migrations/0001_init.sql", contents: migrationSql(spec) },
      { path: "features/contract.ts", contents: featureContract() },
      { path: "lib/types.ts", contents: entityTypes(spec) },
      { path: "lib/supabase.ts", contents: supabaseClient(spec) },
      { path: "app/layout.tsx", contents: layout(spec) },
      { path: "app/page.tsx", contents: homePage(spec) },
      { path: "app/api/health/route.ts", contents: healthRoute(spec) },
    ];

    for (const route of spec.routes) {
      if (!route.feature) continue;
      files.push({
        path: `${routeDirectory(route.path)}/route.ts`,
        contents: featureRoute(spec, route.path),
      });
    }
    return files;
  },
};

function packageJson(spec: ProjectSpec): string {
  return stableJson({
    name: spec.name,
    version: "0.1.0",
    private: true,
    type: "module",
    engines: { node: ">=22.18.0" },
    // Node's own subpath imports, so generated feature modules resolve under
    // bare `node --test` with nothing installed. A tsconfig path alias would
    // typecheck but not run.
    imports: { "#features/*": "./features/*", "#lib/*": "./lib/*" },
    scripts: {
      dev: "next dev",
      build: "next build",
      start: "next start",
      typecheck: "tsc --noEmit",
      test: 'node --test "features/**/*.test.ts"',
    },
    dependencies: DEPENDENCIES,
    devDependencies: DEV_DEPENDENCIES,
  });
}

function tsconfig(): string {
  return stableJson({
    compilerOptions: {
      target: "ES2023",
      lib: ["ES2023", "DOM", "DOM.Iterable"],
      module: "NodeNext",
      moduleResolution: "nodenext",
      allowImportingTsExtensions: true,
      rewriteRelativeImportExtensions: true,
      verbatimModuleSyntax: true,
      erasableSyntaxOnly: true,
      jsx: "preserve",
      noEmit: true,
      strict: true,
      noUncheckedIndexedAccess: true,
      skipLibCheck: true,
      incremental: true,
      plugins: [{ name: "next" }],
    },
    include: ["**/*.ts", "**/*.tsx", ".next/types/**/*.ts"],
    exclude: ["node_modules"],
  });
}

