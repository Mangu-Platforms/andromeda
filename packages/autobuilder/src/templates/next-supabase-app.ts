function readme(spec: ProjectSpec): string {
  const entities = spec.entities.map((e) => `- \`${e.name}\` — ${e.summary}`).join("\n");
  const features = spec.features.map((f) => `- \`${f.id}\` — ${f.summary}`).join("\n");
  const routes = spec.routes
    .map((r) => `- \`${r.method} ${r.path}\` — ${r.summary}`)
    .join("\n");

  return `# ${spec.name}

${spec.summary}

Generated by the Andromeda auto-builder from \`project.yaml\`. The scaffold
(config, schema, row-level security, CI) came from the pinned
\`next-supabase-app\` template; the modules under \`features/\` were generated
and had to pass their own test suite before this repository was proposed for
review.

## Getting started

\`\`\`bash
npm ci
cp .env.example .env.local   # fill in the values
npx supabase db push          # apply supabase/migrations
npm test
npm run dev
\`\`\`

## Data model

${entities || "_No tables._"}

Every table has row-level security enabled. Tables with an owner column carry
owner-scoped policies; tables without one have no policy, which denies all
client access by default.

## Features

${features || "_No generated features._"}

Each feature module exports \`handle(input)\` from \`features/contract.ts\` and
is covered by \`features/<id>.test.ts\`.

## Routes

${routes || "_No routes._"}
`;
}

const featureContract = (): string =>
  `/**
 * The contract between generated business logic and the scaffold.
 *
 * Route handlers, auth and persistence are template-provided; a feature module
 * is a pure function from a request to a response. Keeping the boundary this
 * narrow is what makes generated code testable without a server, a database or
 * a network.
 */
export interface FeatureInput {
  method: string;
  path: string;
  query: Record<string, string>;
  body: unknown;
  /** Authenticated user id, or null for an anonymous request. */
  userId: string | null;
}

export interface FeatureResult {
  status: number;
  body: unknown;
}

export type FeatureHandler = (input: FeatureInput) => Promise<FeatureResult>;
`;

function entityTypes(spec: ProjectSpec): string {
  const blocks = spec.entities.map((entity) => {
    const fields = entity.fields
      .map((f) => `  ${f.name}${f.required ? "" : "?"}: ${tsType(f.type)};`)
      .join("\n");
    return `/** ${entity.summary} */
export interface ${pascal(entity.name)} {
  id: string;
${fields}
  created_at: string;
  updated_at: string;
}`;
  });

  return `// Row types matching supabase/migrations/0001_init.sql.
// Regenerated from project.yaml; edit the spec, not this file.

${blocks.join("\n\n")}${blocks.length ? "\n" : ""}`;
}

function supabaseClient(spec: ProjectSpec): string {
  return `import { createServerClient } from "@supabase/ssr";
import { cookies } from "next/headers";

/**
 * Request-scoped Supabase client for ${spec.name}.
 *
 * This uses the anon key and forwards the caller's session, so every query
 * runs as the signed-in user and row-level security applies. Never swap in the
 * service-role key here — it bypasses RLS entirely.
 */
export async function supabaseServer() {
  const cookieStore = await cookies();
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) {
    throw new Error(
      "NEXT_PUBLIC_SUPABASE_URL and NEXT_PUBLIC_SUPABASE_ANON_KEY must be set",
    );
  }

  return createServerClient(url, key, {
    cookies: {
      getAll: () => cookieStore.getAll(),
      setAll: (list) => {
        for (const { name, value, options } of list) {
          cookieStore.set(name, value, options);
        }
      },
    },
  });
}
`;
}

